/**
 * Artkatalog med de ekologiska parametrar modellen behöver.
 *
 * Siffrorna bygger på svensk mykologisk litteratur och fältdata: när arterna
 * fruktifierar i Mellansverige, vilka trädslag de bildar mykorrhiza med, och
 * hur lång fördröjningen är mellan regn och fruktkropp. Kantarellen är den
 * långsammaste av dem — mycelet behöver ungefär två till tre veckors uthållig
 * markfukt innan något sticker upp. Det är därför "det regnade igår" inte är
 * en bra kantarellprognos, men "det regnade rejält för sexton dagar sen" är det.
 */

