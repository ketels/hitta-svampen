/** Hjälp: dagnummer från månad/dag. */
const d = (manad: number, dag: number) =>
  Math.round((new Date(Date.UTC(2001, manad - 1, dag)).getTime() - Date.UTC(2001, 0, 1)) / 864e5) + 1

